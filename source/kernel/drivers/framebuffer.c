#include "../include/framebuffer.h"
#include "../include/string.h"

static uint32_t *fb_addr = NULL;
static uint32_t fb_w = 0;
static uint32_t fb_h = 0;
static uint32_t fb_pitch = 0;
static uint16_t fb_bpp = 0;

static uint32_t cursor_x = 0;
static uint32_t cursor_y = 0;

// Embedded basic 8x16 bitmap font for ASCII 32..126
extern const uint8_t font8x16[95][16];

void fb_init(void *addr, uint32_t width, uint32_t height, uint32_t pitch, uint16_t bpp) {
    fb_addr = (uint32_t*)addr;
    fb_w = width;
    fb_h = height;
    fb_pitch = pitch;
    fb_bpp = bpp;
    cursor_x = 0;
    cursor_y = 0;

    fb_clear(COLOR_BLACK);
}

uint32_t fb_get_width(void) { return fb_w; }
uint32_t fb_get_height(void) { return fb_h; }
void *fb_get_buffer(void) { return (void*)fb_addr; }

void fb_put_pixel(uint32_t x, uint32_t y, uint32_t color) {
    if (!fb_addr || x >= fb_w || y >= fb_h) return;
    fb_addr[y * (fb_pitch / 4) + x] = color;
}

void fb_fill_rect(uint32_t x, uint32_t y, uint32_t width, uint32_t height, uint32_t color) {
    if (!fb_addr) return;
    for (uint32_t cy = 0; cy < height && (y + cy) < fb_h; cy++) {
        for (uint32_t cx = 0; cx < width && (x + cx) < fb_w; cx++) {
            fb_addr[(y + cy) * (fb_pitch / 4) + (x + cx)] = color;
        }
    }
}

void fb_clear(uint32_t color) {
    fb_fill_rect(0, 0, fb_w, fb_h, color);
    cursor_x = 0;
    cursor_y = 0;
}

void fb_draw_char(char c, uint32_t x, uint32_t y, uint32_t fg, uint32_t bg) {
    if (!fb_addr) return;
    if (c < 32 || c > 126) c = ' ';
    const uint8_t *glyph = font8x16[(int)c - 32];

    for (int cy = 0; cy < 16; cy++) {
        uint8_t row = glyph[cy];
        for (int cx = 0; cx < 8; cx++) {
            if ((row >> (7 - cx)) & 1) {
                fb_put_pixel(x + cx, y + cy, fg);
            } else if (bg != COLOR_BLACK) {
                fb_put_pixel(x + cx, y + cy, bg);
            }
        }
    }
}

static void fb_scroll(void) {
    if (!fb_addr) return;
    uint32_t row_size = (fb_pitch / 4);
    size_t copy_pixels = (fb_h - 16) * row_size;
    memcpy(fb_addr, &fb_addr[16 * row_size], copy_pixels * sizeof(uint32_t));
    fb_fill_rect(0, fb_h - 16, fb_w, 16, COLOR_BLACK);
}

void fb_print_color(const char *str, uint32_t fg, uint32_t bg) {
    if (!fb_addr) return;
    while (*str) {
        char c = *str++;
        if (c == '\n') {
            cursor_x = 0;
            cursor_y += 16;
            if (cursor_y + 16 > fb_h) {
                fb_scroll();
                cursor_y = fb_h - 16;
            }
            continue;
        } else if (c == '\r') {
            cursor_x = 0;
            continue;
        } else if (c == '\t') {
            cursor_x = (cursor_x + 32) & ~31;
            continue;
        }

        fb_draw_char(c, cursor_x, cursor_y, fg, bg);
        cursor_x += 8;
        if (cursor_x + 8 > fb_w) {
            cursor_x = 0;
            cursor_y += 16;
            if (cursor_y + 16 > fb_h) {
                fb_scroll();
                cursor_y = fb_h - 16;
            }
        }
    }
}

void fb_print(const char *str) {
    fb_print_color(str, COLOR_WHITE, COLOR_BLACK);
}

void fb_println(const char *str) {
    fb_print(str);
    fb_print("\n");
}

void fb_draw_box(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t bg_color, uint32_t border_color, const char *title, const char *text) {
    fb_fill_rect(x, y, w, h, bg_color);
    // Draw 2px border
    fb_fill_rect(x, y, w, 2, border_color);
    fb_fill_rect(x, y + h - 2, w, 2, border_color);
    fb_fill_rect(x, y, 2, h, border_color);
    fb_fill_rect(x + w - 2, y, 2, h, border_color);

    if (title) {
        uint32_t tx = x + (w / 2) - ((strlen(title) * 8) / 2);
        for (size_t i = 0; title[i] != '\0'; i++) {
            fb_draw_char(title[i], tx + i * 8, y + 8, COLOR_YELLOW, bg_color);
        }
    }

    if (text) {
        uint32_t mx = x + 16;
        uint32_t my = y + 36;
        for (size_t i = 0; text[i] != '\0'; i++) {
            if (text[i] == '\n') {
                mx = x + 16;
                my += 18;
                continue;
            }
            fb_draw_char(text[i], mx, my, COLOR_WHITE, bg_color);
            mx += 8;
        }
    }
}

